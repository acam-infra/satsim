"""Isolate the effect of arrival synchronization after fixed initial placement.

Run from the repository root: python scripts/m5_hotspots/experiment.py
Only NumPy is required. The placement traces are generated by orbit_study.py.
"""
import json
from collections import defaultdict

import numpy as np

from orbit_study import COLD, DT, N, PHASES, geometry, run, traffic

MAX_SHIFT_S = 360
THRESHOLDS = (60, 120, 240)
REPEATS = 8


def shift_backlog(backlog, offsets_s):
    """Delay every admission on a node equally, including its initial burst.

    For this replay, nodes are independent, time-invariant and initially empty.
    Shifting their full backlog trajectories is equivalent to delaying their
    admissions and rerunning the compute queues.
    """
    shifted = np.zeros((len(backlog) + MAX_SHIFT_S // DT, N))
    for node, seconds in enumerate(offsets_s):
        start = int(seconds) // DT
        shifted[start:start + len(backlog), node] = backlog[:, node]
    return shifted


def metrics(backlog, threshold):
    hot = backlog >= threshold
    simultaneous = hot.sum(axis=1)
    hot_samples = int(hot.sum())
    has_low_backlog_node = np.any(backlog < COLD, axis=1)
    return {
        "any_hot_minutes": float((simultaneous > 0).sum() * DT / 60),
        "half_fleet_hot_minutes": float((simultaneous >= N // 2).sum() * DT / 60),
        "hot_node_minutes": float(hot_samples * DT / 60),
        "hot_node_time_without_low_backlog_peer_pct": (
            float(100 * simultaneous[~has_low_backlog_node].sum() / hot_samples)
            if hot_samples else 0.0
        ),
    }


def replay_admissions(placements, ticks, offsets_s):
    """Compute the queue trajectory directly from delayed per-node admissions."""
    work = np.zeros((ticks, N))
    for admitted_s, _, _, _, node, gpu_s in placements:
        tick = (admitted_s + int(offsets_s[node])) // DT
        work[tick, node] += gpu_s
    backlog = np.zeros_like(work)
    backlog[0] = work[0]
    for tick in range(1, ticks):
        backlog[tick] = np.maximum(backlog[tick - 1] - DT, 0) + work[tick]
    return backlog


def main():
    rows = defaultdict(list)
    for phase in PHASES:
        t, direct, hops, passes, _ = geometry(phase)
        # The toy constellation permits interpreting every low-backlog peer as
        # reachable by topology. The replay does not model link throughput.
        assert np.all(hops < 99)
        for jobs in (72, 144):
            arrivals, _, _ = traffic(t, direct, passes, jobs)
            summary, backlog, placements = run(t, direct, hops, arrivals, "routed_rr")
            assert summary["completed"] == summary["admitted"]
            assert not np.any(backlog[-1])
            unshifted = shift_backlog(backlog, np.zeros(N, dtype=int))
            rng = np.random.default_rng(512 + phase + jobs)
            original = {threshold: metrics(unshifted, threshold) for threshold in THRESHOLDS}
            for threshold in THRESHOLDS:
                rows[jobs, threshold, "original"].append(original[threshold])
            for rep in range(REPEATS):
                cluster_offsets = rng.permutation(np.arange(4) * (MAX_SHIFT_S // 3))
                offsets = np.repeat(cluster_offsets, N // 4)
                staggered = shift_backlog(backlog, offsets)
                if rep == 0:
                    replayed = replay_admissions(placements, len(staggered), offsets)
                    np.testing.assert_allclose(staggered, replayed, atol=1e-8)
                np.testing.assert_allclose(staggered.sum(axis=0), unshifted.sum(axis=0))
                np.testing.assert_allclose(staggered.max(axis=0), unshifted.max(axis=0))
                for threshold in THRESHOLDS:
                    current = metrics(staggered, threshold)
                    assert current["hot_node_minutes"] == original[threshold]["hot_node_minutes"]
                    rows[jobs, threshold, "staggered"].append(current)
    result = []
    for (jobs, threshold, arm), samples in sorted(rows.items()):
        mean = {k: round(float(np.mean([s[k] for s in samples])), 3) for k in samples[0]}
        result.append(dict(jobs_per_pass=jobs, threshold_gpu_s=threshold, arm=arm,
                           replays=len(samples), **mean))
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
